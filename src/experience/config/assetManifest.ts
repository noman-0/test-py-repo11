/**
 * Single registry for every replaceable visual asset used by the website and the 3D experience.
 *
 * Replacing an asset = drop a new file at the same path (or change the path here). Application
 * logic never hard-codes these paths. Each entry records its origin and licence.
 *
 * Origins:
 *  - "excelsa-guide": cropped/derived from the official Excelsa.pdf brand guide (client-owned).
 *  - "generated":     produced by this project's own scripts/code (no third-party rights).
 *  - "cc0":           third-party CC0 asset - see docs/ASSET_LICENSES.md for source + verification.
 */
export type AssetOrigin = "excelsa-guide" | "generated" | "cc0";

export interface AssetEntry {
  path: string;
  origin: AssetOrigin;
  licence: string;
  /** True for temporary visuals that must be replaced by client originals. */
  placeholder?: boolean;
  note?: string;
}

const guide = (path: string, note?: string): AssetEntry => ({
  path,
  origin: "excelsa-guide",
  licence: "Client brand asset (Excelsa Brand Identity Style Guide)",
  note,
});

